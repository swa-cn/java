/** 按分类 id 取知识条目；categoryId 为空或 'all' 时返回全部 */
export function articlesOf(categoryId) {
  const list = KNOWLEDGE_ARTICLES
  if (!categoryId || categoryId === 'all') return list
  return list.filter((a) => a.cat === categoryId || a.cat === 'all')
}

/** 全文搜索知识：标题 / 摘要 / 标签 / 正文匹配 */
export function searchArticles(keyword) {
  return searchIn(KNOWLEDGE_ARTICLES, keyword)
}

/**
 * 对「任意来源」的文章列表做全文搜索（远端列表与静态兜底共用同一套逻辑）。
 * 匹配范围：标题 / 摘要 / 标签 / 正文小节
 */
export function searchIn(list, keyword) {
  const k = String(keyword || '').trim().toLowerCase()
  const src = Array.isArray(list) ? list : []
  if (!k) return []
  return src.filter((a) => {
    const haystack = [
      a.title, a.summary, ...(a.tags || []),
      ...(a.sections || []).flatMap((s) => [s.h, s.p])
    ].join('\n').toLowerCase()
    return haystack.includes(k)
  })
}
